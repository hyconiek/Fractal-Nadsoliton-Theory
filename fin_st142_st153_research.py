    rank=gf2_rank([x for x in equations if x],len(edges))
    return {"nodes":n,"edges":[list(x) for x in edges],"path_counts":[len(x) for x in paths],
            "parity_obstruction_nodes":sorted(set(parity_obstruction)),"linear_equations":len([x for x in equations if x]),
            "GF2_rank":rank,"coherent_twist_count":0 if parity_obstruction else 2**(len(edges)-rank)}


