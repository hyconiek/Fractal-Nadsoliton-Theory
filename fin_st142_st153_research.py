def all_paths(n,edges,source=0):
    incoming=[[] for _ in range(n)]
    for e,(u,v,m) in enumerate(edges): incoming[v].append((u,e,m%2))
    paths=[[] for _ in range(n)]; paths[source]=[(1,0)]
    for v in range(source+1,n):
        for u,e,aedge in incoming[v]:
            for a,mask in paths[u]: paths[v].append((aedge*a,(aedge*mask)^(1<<e)))
    return paths


def gf2_rank(rows,ncols):
    rows=list(rows); rank=0
    for col in range(ncols):
        pivot=next((i for i in range(rank,len(rows)) if (rows[i]>>col)&1),None)
        if pivot is None: continue
        rows[rank],rows[pivot]=rows[pivot],rows[rank]
        for i in range(len(rows)):
            if i!=rank and ((rows[i]>>col)&1): rows[i]^=rows[rank]
        rank+=1
    return rank


def dag_certificate(n,edges):
    paths=all_paths(n,edges); equations=[]; parity_obstruction=[]
