def hmm_sequence_likelihoods(n: int, P: np.ndarray, pi: np.ndarray, emissions: np.ndarray) -> np.ndarray:
    # Rows are all binary strings in lexicographic recursion; columns are hidden-state forward weights.
    if n < 1:
        raise ValueError("n must be positive")
    forward = np.vstack([pi * emissions[:, 0], pi * emissions[:, 1]])
    for _ in range(1, n):
        pred = forward @ P
        forward = np.vstack([pred * emissions[:, 0], pred * emissions[:, 1]])
    return np.sum(forward, axis=1)


def hidden_pair_transfer(P, p0, p1, s=.5):
    t = np.zeros((4, 4)); initial = np.zeros(4)
    pi = np.array([2/3, 1/3])
    for z, zp in itertools.product(range(2), repeat=2):
        c0 = p0[z]**s * p1[zp]**(1-s) + (1-p0[z])**s * (1-p1[zp])**(1-s)
        initial[2*z+zp] = pi[z]**s * pi[zp]**(1-s) * c0
        for w, wp in itertools.product(range(2), repeat=2):
            c = p0[w]**s * p1[wp]**(1-s) + (1-p0[w])**s * (1-p1[wp])**(1-s)
            t[2*z+zp, 2*w+wp] = P[z, w]**s * P[zp, wp]**(1-s) * c
    return initial, t


