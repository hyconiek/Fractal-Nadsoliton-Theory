def bell_number(n: int) -> int:
    bell = [0]*(n+1); bell[0] = 1
    for i in range(1, n+1):
        bell[i] = sum(math.comb(i-1, k)*bell[k] for k in range(i))
    return bell[n]


def extremality_constraint_rank(h: np.ndarray, tol=1e-9) -> tuple[int, int]:
    vals, vecs = np.linalg.eigh(h); keep = vals > tol
    v = vecs[:, keep] * np.sqrt(vals[keep])[None, :]
    r = v.shape[1]; pairs = [(i, i) for i in range(N)] + [(i, j) for i in range(N) for j in range(i+1, N) if abs(h[i, j]) < tol]
    cols = []
    for a in range(r):
        for b in range(a, r):
            col = []
            for i, j in pairs:
                value = v[i, a]*v[j, b]
                if a != b: value += v[i, b]*v[j, a]
                col.append(value)
            cols.append(col)
    rank = np.linalg.matrix_rank(np.array(cols).T, tol=tol) if cols else 0
    return r, int(rank)


def partition_matrix(blocks: list[list[int]]) -> np.ndarray:
    h = np.zeros((N, N))
    for block in blocks:
        for i in block:
            for j in block: h[i, j] = 1/N
    return h


