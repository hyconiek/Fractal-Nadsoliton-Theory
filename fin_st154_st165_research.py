def native(x: Any) -> Any:
    if isinstance(x, dict): return {str(k): native(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)): return [native(v) for v in x]
    if isinstance(x, np.ndarray): return native(x.tolist())
    if isinstance(x, (np.floating, np.integer)): return x.item()
    return x


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_packet(path: Path, data: dict) -> str:
    path.write_text(json.dumps(native(data), indent=2, sort_keys=True), encoding="utf-8")
    return sha(path)


def commutant_dimension(generators: Iterable[np.ndarray], tol: float = 1e-9) -> int:
    generators = [np.asarray(g, dtype=complex) for g in generators]
    d = generators[0].shape[0]
    eye = np.eye(d)
    equations = [np.kron(eye, g) - np.kron(g.T, eye) for g in generators]
    rank = np.linalg.matrix_rank(np.vstack(equations), tol=tol)
    return int(d * d - rank)


