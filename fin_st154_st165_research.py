def algebra_span_dimension(generators: list[np.ndarray], tol=1e-9) -> int:
    d = generators[0].shape[0]
    basis = [np.eye(d, dtype=complex)]
    changed = True
    while changed:
        changed = False
        candidates = basis + [b @ g for b in basis for g in generators]
        new_basis = []
        for x in candidates:
            trial = new_basis + [x]
            rank = np.linalg.matrix_rank(np.column_stack([z.reshape(-1) for z in trial]), tol=tol)
            if rank > len(new_basis): new_basis.append(x)
        if len(new_basis) > len(basis): changed = True
        basis = new_basis
    return len(basis)


