def circulant_subclass_witness(p2786: dict[str, Any]) -> dict[str, Any]:
    raw_rows, classes = quotient_connected_circulants()
    locals_ = local_representatives(p2786)
    class_rows = []
    for klass in classes:
        matching_locals = [row["representative"] for row in locals_ if isomorphic(klass["representative_edges"], row["edges"], N)]
        aut_size = automorphism_count(klass["representative_edges"], N)
        graph6 = graph6_encode(list(klass["representative_edges"]), n=N)
        class_rows.append({
            "class_index": klass["class_index"],
            "representative_jumps": klass["representative_jumps"],
            "jump_pair_members": klass["jump_pair_members"],
            "jump_pair_member_count": len(klass["jump_pair_members"]),
            "matching_p2786_local_representatives": matching_locals,
            "represented_in_p2786_local_set": bool(matching_locals),
            "edge_count": len(klass["representative_edges"]),
            "automorphism_group_size": aut_size,
            "orbit_size_by_orbit_stabilizer": math.factorial(N) // aut_size,
            "graph6": graph6,
            "graph6_sha256": hashlib.sha256(graph6.encode("ascii")).hexdigest(),
            "adjacency_charpoly_coefficients": [int(c) for c in charpoly_expr(klass["representative_edges"], N, "adjacency").all_coeffs()],
        })
    pair_rows = []
    for left_index, left in enumerate(classes):
        for right_index in range(left_index + 1, len(classes)):
            right = classes[right_index]
            pair_rows.append({
                "left_class_index": left["class_index"],
                "right_class_index": right["class_index"],
                "isomorphic": isomorphic(left["representative_edges"], right["representative_edges"], N),
            })
    connected_rows = [row for row in raw_rows if row["connected"]]
    disconnected_rows = [row for row in raw_rows if not row["connected"]]
    return {
        "source_class": "All undirected C16 two-jump 4-regular circulants generated by {±a, ±b}, 1 <= a < b <= 7.",
        "raw_jump_pair_count": len(raw_rows),
        "connected_jump_pair_count": len(connected_rows),
        "disconnected_jump_pair_count": len(disconnected_rows),
        "connected_isomorphism_class_count": len(classes),
        "pair_count_after_quotient": len(pair_rows),
        "raw_jump_pair_rows": [{key: value for key, value in row.items() if key != "edges"} for row in raw_rows],
        "class_rows": class_rows,
        "pairwise_class_rows": pair_rows,
        "all_connected_classes_pairwise_nonisomorphic": all(not row["isomorphic"] for row in pair_rows),
        "all_connected_classes_represented_in_p2786_local_set": all(row["represented_in_p2786_local_set"] for row in class_rows),
        "finite_certificate_statement": "The complete C16 two-jump circulant subclass has 21 raw jump pairs, 18 connected cases, 5 isomorphism classes, and all 5 classes are already represented among the P2786 seven local representatives.",
    }


