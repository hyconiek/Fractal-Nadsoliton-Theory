def sha(path: Path) -> str | None:
    return hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else None


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"missing": True, "path": rel(path)}


def circulant_edges(jumps: tuple[int, int], n: int = N) -> tuple[tuple[int, int], ...]:
    edges = set()
    for vertex in range(n):
        for jump in jumps:
            edges.add(tuple(sorted((vertex, (vertex + jump) % n))))
            edges.add(tuple(sorted((vertex, (vertex - jump) % n))))
    return normalize_edges(edges)


def connected(edges: tuple[tuple[int, int], ...], n: int = N) -> bool:
    adj = [set() for _ in range(n)]
    for a, b in edges:
        adj[a].add(b)
        adj[b].add(a)
    seen = {0}
    stack = [0]
    while stack:
        node = stack.pop()
        for nxt in adj[node] - seen:
            seen.add(nxt)
            stack.append(nxt)
    return len(seen) == n


def degree_sequence(edges: tuple[tuple[int, int], ...], n: int = N) -> list[int]:
    degree = [0] * n
    for a, b in edges:
        degree[a] += 1
        degree[b] += 1
    return degree


def quotient_connected_circulants() -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    raw_rows = []
    classes: list[dict[str, Any]] = []
    for jumps in combinations(range(1, 8), 2):
        edges = circulant_edges(jumps)
        row = {
            "jumps": list(jumps),
            "edge_count": len(edges),
            "degree_sequence": degree_sequence(edges),
            "connected": connected(edges),
            "edges": edges,
        }
        raw_rows.append(row)
        if not row["connected"]:
            continue
        for klass in classes:
            if isomorphic(edges, klass["representative_edges"], N):
                klass["jump_pair_members"].append(list(jumps))
                break
        else:
            classes.append({
                "class_index": len(classes),
                "representative_jumps": list(jumps),
                "representative_edges": edges,
                "jump_pair_members": [list(jumps)],
            })
    return raw_rows, classes


