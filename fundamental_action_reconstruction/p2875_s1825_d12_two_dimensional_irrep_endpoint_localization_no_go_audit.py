    reconstructed: list[float] = []
    for endpoint in ENDPOINTS:
        value = sum(coefficients[mode] * cmath.exp(2j * math.pi * mode * endpoint / MODULUS) for mode in ENDPOINTS)
        reconstructed.append(round(value.real, 12))
    return reconstructed


